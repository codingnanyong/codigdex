const CATALOGS: Readonly<Record<Locale, Readonly<Record<MessageKey, string>>>> = { ko, en };

export type MessageParams = Readonly<Record<string, string | number>>;

/** Looks up interface copy and fills `{name}` placeholders. */
export function translate(locale: Locale, key: MessageKey, params: MessageParams = {}): string {
  return CATALOGS[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match
  );
}

export function messageCatalog(locale: Locale): Readonly<Record<MessageKey, string>> {
  return CATALOGS[locale];
}
