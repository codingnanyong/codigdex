import { readFileSync, writeFileSync } from "node:fs";
import { MUSIC_SCORES } from "../src/musicScores.ts";

const file = new URL("../src/music.ts", import.meta.url);
const output = `// Generated by scripts/generate-music-manifest.mjs. Runtime metadata only.\n` +
  `export interface MusicTrack { region: string; title: string; assetKey: string; duration: number }\n` +
  `const track = (region: string, title: string, assetKey: string, duration: number): MusicTrack => ({ region, title, assetKey, duration });\n` +
  `export const MUSIC_TRACKS: readonly MusicTrack[] = [\n${MUSIC_SCORES.map(s => `  track(${[s.region, s.title, s.assetKey, 16 * s.beats * 60 / s.bpm].map(v => JSON.stringify(v)).join(", ")}),`).join("\n")}\n];\n` +
  `const byRegion = new Map(MUSIC_TRACKS.map(track => [track.region, track]));\n` +
  `export const musicTrack = (region: string | undefined) => region ? byRegion.get(region) : undefined;\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(file, "utf8") !== output) throw new Error("Music runtime manifest is stale. Run npm run generate:music --workspace @codigdex/game-assets.");
} else writeFileSync(file, output);
