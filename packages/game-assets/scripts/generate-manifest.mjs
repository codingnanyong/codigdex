import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const filesRoot = path.join(packageRoot, "files");
const manifestPath = path.join(packageRoot, "src/manifest.generated.ts");
const assetExtensions = new Set([".png", ".webp", ".jpg", ".svg"]);

async function collectKeys(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const keys = [];
  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) keys.push(...(await collectKeys(entryPath)));
    else if (assetExtensions.has(path.extname(entry.name))) {
      keys.push(path.relative(filesRoot, entryPath).split(path.sep).join("/"));
    }
  }
  return keys;
}

const keys = (await collectKeys(filesRoot)).sort();
const manifest = [
  "// Generated by scripts/generate-manifest.mjs. Do not edit by hand.",
  "export const ASSET_KEYS = [",
  ...keys.map((key) => `  ${JSON.stringify(key)},`),
  "] as const;",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = (await readFile(manifestPath, "utf8").catch(() => "")).replace(/\r\n/g, "\n");
  if (current !== manifest) {
    console.error(
      "src/manifest.generated.ts is out of date. Run: npm run generate --workspace @codigdex/game-assets"
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(manifestPath, manifest);
  console.log(`Wrote ${keys.length} asset keys.`);
}
