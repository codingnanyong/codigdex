import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { WALLPAPERS } from "../../packages/game-assets/src/visuals.ts";

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = path.resolve(mobileRoot, "..");
const manifestPath = path.join(repositoryRoot, "packages/game-assets/src/manifest.generated.ts");
const outputPath = path.join(mobileRoot, "src/assets.generated.ts");
const manifest = await readFile(manifestPath, "utf8");
// Share the four web originals; keep unrelated career archives out of Metro.
const keys = [...manifest.matchAll(/^  "([^"]+)",$/gm)].map((match) => match[1])
  .filter((key) => (key.startsWith("monsters/") && !/-(?:evolution-(?:guide|sheet)-v\d+|specimen(?:-v\d+)?)\.png$/.test(key)) || Object.values(WALLPAPERS).includes(key));

if (keys.length === 0) throw new Error(`No asset keys found in ${manifestPath}`);

const entries = keys.map(
  (key) => `  ${JSON.stringify(key)}: require(${JSON.stringify(`../../packages/game-assets/files/${key}`)}),`
);
const generated = `// Generated by scripts/generate-asset-map.mjs. Do not edit by hand.\n` +
  `import type { ImageSourcePropType } from "react-native";\n` +
  `import type { AssetKey } from "@codigdex/game-assets/manifest";\n\n` +
  `export const MOBILE_ASSETS = {\n${entries.join("\n")}\n` +
  `} satisfies Readonly<Partial<Record<AssetKey, ImageSourcePropType>>>;\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) throw new Error("Mobile asset map is stale. Run npm run generate:assets --workspace @codigdex/mobile.");
} else {
  await writeFile(outputPath, generated, "utf8");
  console.log(`Generated ${keys.length} mobile asset imports.`);
}
