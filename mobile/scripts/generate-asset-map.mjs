import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { WALLPAPERS } from "../../packages/game-assets/src/visuals.ts";
import { SECONDARY_MOBILE_ART } from "../../packages/game-assets/src/secondaryArt.ts";
import { OPEN_SOURCE_MOBILE_ART } from "../../packages/game-assets/src/openSourceArt.ts";

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = path.resolve(mobileRoot, "..");
const manifestPath = path.join(repositoryRoot, "packages/game-assets/src/manifest.generated.ts");
const outputPath = path.join(mobileRoot, "src/assets.generated.ts");
const manifest = await readFile(manifestPath, "utf8");
const allKeys = [...manifest.matchAll(/^  "([^"]+)",$/gm)].map((match) => match[1]);
const wallpapers = new Set([...Object.values(WALLPAPERS), ...SECONDARY_MOBILE_ART, ...OPEN_SOURCE_MOBILE_ART]);
const keys = allKeys.filter((key) => (key.startsWith("monsters/") && key.endsWith(".png") &&
  !/evolution-(?:guide|sheet)|concept-sheet|specimen|\/reference\/|\/archives\//.test(key) &&
  !(key.startsWith("monsters/mastery/") && /guardian-[1-5]\.png$/.test(key) && allKeys.includes(key.replace(/\.png$/, "-v3.png")))) ||
  /^characters\/promotion\/[^/]+\/guide-v1\.png$/.test(key) || wallpapers.has(key));

if (keys.length === 0) throw new Error(`No asset keys found in ${manifestPath}`);

const entries = keys.map(
  (key) => `  ${JSON.stringify(key)}: () => require(${JSON.stringify(`../../packages/game-assets/files/${wallpapers.has(key) ? `wallpapers/mobile/${key.replaceAll("/", "--")}` : key}`)}),`
);
const generated = `// Generated by scripts/generate-asset-map.mjs. Do not edit by hand.\n` +
  `import type { ImageSourcePropType } from "react-native";\n` +
  `import type { AssetKey } from "@codigdex/game-assets/manifest";\n\n` +
  `export const MOBILE_ASSETS = {\n${entries.join("\n")}\n` +
  `} satisfies Readonly<Partial<Record<AssetKey, () => ImageSourcePropType>>>;\n`;

const current = await readFile(outputPath, "utf8").catch(() => "");
const audioKeys = allKeys.filter(key => key.startsWith("audio/music/") && key.endsWith(".mp3"));
const audioPath = path.join(mobileRoot, "src/audio.generated.ts");
const audioGenerated = `// Generated by scripts/generate-asset-map.mjs. Do not edit by hand.\nexport const AUDIO_ASSETS: Readonly<Record<string, () => number>> = {\n${audioKeys.map(key => `  ${JSON.stringify(key)}: () => require(${JSON.stringify(`../../packages/game-assets/files/${key}`)}),`).join("\n")}\n};\n`;
const currentAudio = await readFile(audioPath, "utf8").catch(() => "");
if (process.argv.includes("--check")) {
  if (currentAudio !== audioGenerated) throw new Error("Mobile audio map is stale. Run npm run generate:assets --workspace @codigdex/mobile.");
  if (current !== generated) throw new Error("Mobile asset map is stale. Run npm run generate:assets --workspace @codigdex/mobile.");
} else if (current !== generated) {
  await writeFile(outputPath, generated, "utf8");
  console.log(`Generated ${keys.length} mobile asset imports.`);
} else {
  console.log(`Mobile asset map is current (${keys.length} imports).`);
}
if (!process.argv.includes("--check") && currentAudio !== audioGenerated) {
  await writeFile(audioPath, audioGenerated, "utf8");
  console.log(`Generated ${audioKeys.length} mobile audio imports.`);
}
